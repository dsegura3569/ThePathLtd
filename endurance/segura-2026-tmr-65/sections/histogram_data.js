const AXIS_MIN = -45, AXIS_MAX = 45, STEP = 0.5;
const full = [];
for (let g = AXIS_MIN; g <= AXIS_MAX + 0.001; g += STEP) {
  const rounded = Math.round(g * 10) / 10;
  const found = bins.find(b => Math.abs(b.grade - rounded) < 0.01);
  full.push({ grade: rounded, miles: found ? found.miles : 0 });
}

function histGradeColor(g) {
  if (g >= 20) return "#7B1010";
  if (g >= 15) return "#A32D2D";
  if (g >= 8)  return "#E8943A";
  if (g >= 0)  return "#3CB897";
  if (g >= -8) return "#7DD3FC";
  if (g >= -15) return "#4A9FE8";
  if (g >= -20) return "#1460A8";
  return "#0C3B6E";
}
